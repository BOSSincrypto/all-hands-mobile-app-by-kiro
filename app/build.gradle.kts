/**
 * Release signing is read from keystore.properties (git-ignored) or, in CI, from
 * environment variables. When neither is present the release build falls back to
 * the debug identity so `assembleRelease` still succeeds for personal sideloading.
 */
val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) keystorePropsFile.inputStream().use { load(it) }
}

fun signingValue(key: String, env: String): String? =
    keystoreProps.getProperty(key) ?: System.getenv(env)

val releaseStorePath = signingValue("storeFile", "RELEASE_STORE_FILE")
val hasReleaseSigning = releaseStorePath != null && file(releaseStorePath).exists()

